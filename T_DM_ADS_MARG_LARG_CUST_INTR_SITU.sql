--STEP 0.0系统参数
SET hivevar:MTH = substring(${hivevar:RQ},1,6);

SELECT ${hivevar:RQ} FROM SYSTEM.DUAL;
SELECT ${hivevar:MTH} FROM SYSTEM.DUAL;

--SETP.1.0 删除表数据
SELECT 'SETP.1.0 删除【DM_FORT.T_DM_ADS_MARG_LARG_CUST_INTR_SITU】表数据' FROM SYSTEM.DUAL;
DELETE FROM DM_FORT.T_DM_ADS_MARG_LARG_CUST_INTR_SITU WHERE MTH=${hivevar:MTH} AND BUSI_DATE=${hivevar:RQ};

--SETP.2.0 处理逻辑
SELECT 'SETP.2.0 处理逻辑' FROM SYSTEM.DUAL;
INSERT INTO DM_FORT.T_DM_ADS_MARG_LARG_CUST_INTR_SITU
(
DEPT_NUM,
DEPT_NAME,
CUST_NUM,
CUST_NAME,
FIN_LIAB,
FIN_LIAB_TYPE,
PCT_MARG_BAL_RATI,
FIN_AROR_INTR,
ADJ_DATE,
MTH,
BUSI_DATE
)
SELECT T1.DEPT_NUM,
       T2.ORG_ABBR AS DEPT_NAME,
       T1.CUST_NUM,
       T3.CN_ABBR AS CUST_NAME,
       T1.FIN_LIAB,
       CASE WHEN T1.FIN_LIAB>=5000000 AND T1.FIN_LIAB<10000000 THEN '1'
            WHEN T1.FIN_LIAB>=10000000 AND T1.FIN_LIAB<30000000 THEN '2'
            WHEN T1.FIN_LIAB>=30000000 AND T1.FIN_LIAB<50000000 THEN '3'
            WHEN T1.FIN_LIAB>=50000000 THEN '4'
       ELSE NULL END AS FIN_LIAB_TYPE,
       T1.PCT_MARG_BAL_RATI,
       T1.FIN_AROR_INTR,
       NVL(T1.BUSI_DATE,'-') AS ADJ_DATE,
       ${hivevar:MTH} AS MTH,
       ${hivevar:RQ} AS BUSI_DATE
FROM (SELECT A.DEPT_NUM,
             A.CUST_NUM,
             A.CUST_NAME,
             A.FIN_LIAB,
             A.FIN_LIAB/B.MARG_BAL AS PCT_MARG_BAL_RATI,
             C.FIN_AROR_INTR,
             C.BUSI_DATE
      FROM (SELECT '1' AS CNT,DEPT_NUM,CUST_NUM,CUST_NAME,FIN_LIAB
            FROM ADP_DWS.T_DWS_CUST_MARG_D 
            WHERE MTH=${hivevar:MTH} 
                  AND BUSI_DATE=TRD_DATE 
                  AND BUSI_DATE=${hivevar:RQ} 
                  AND FIN_LIAB>=5000000
                  ) A
      LEFT JOIN (SELECT '1' AS CNT,SUM(MARG_BAL) AS MARG_BAL FROM ADP_DWS.T_DWS_CUST_MARG_D WHERE MTH=${hivevar:MTH} AND BUSI_DATE=TRD_DATE AND BUSI_DATE=${hivevar:RQ}) B
      ON A.CNT=B.CNT
      LEFT JOIN (SELECT CUST_NUM,
                        IF(ADJ_INTR_TYPE=1,'-',BUSI_DATE) AS BUSI_DATE,
                        FIN_AROR_INTR,
                        ADJ_INTR_TYPE 
                 FROM (SELECT ROW_NUMBER()OVER(PARTITION BY CUST_NUM ORDER BY BUSI_DATE DESC) AS RN,T.* 
                       FROM DM_FORT.T_DM_ADS_MARG_PSLZ_INTR_T0 T 
                       WHERE BUSI_DATE<=${hivevar:RQ} 
                             AND ADJ_INTR_TYPE<>3) 
                 WHERE RN=1) C
      ON A.CUST_NUM=C.CUST_NUM
      ) T1
INNER JOIN (SELECT REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(DEPT_NAME,'东海证券股份有限公司',''),'东海证券',''),'证券营业部',''),'营业部','') AS ORG_ABBR,
                   DEPT_NAME,
                   ORG_NUM
            FROM DWD_DHZQ.T_DWD_PTY_SECU_DEPT_DHZQ)T2
ON T1.DEPT_NUM=T2.ORG_NUM
INNER JOIN (SELECT * FROM ADP_DWD.T_DWD_PTY_CUST WHERE LENGTH(CUST_NUM)>0) T3
ON T1.CUST_NUM=T3.CUST_NUM;
